/**
 * Returns villages from the county's village list that are within maxKm of the given town.
 * Falls back to all villages in the county if the town has no known coordinates.
 */
export function getVillagesNearTown(county, townName, allVillages, maxKm = 20) {
  const townCoords = TOWN_VILLAGE_COORDS[townName];
  if (!townCoords) return allVillages; // no coords, return all

  return allVillages.filter(v => {
    if (v === townName) return false; // exclude the town itself
    const vCoords = TOWN_VILLAGE_COORDS[v];
    if (!vCoords) return true; // no coords for village, include by default
    const R = 6371;
    const dLat = ((vCoords.lat - townCoords.lat) * Math.PI) / 180;
    const dLng = ((vCoords.lng - townCoords.lng) * Math.PI) / 180;
    const a = Math.sin(dLat / 2) ** 2 +
      Math.cos((townCoords.lat * Math.PI) / 180) *
      Math.cos((vCoords.lat * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
    const dist = R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    return dist <= maxKm;
  });
}